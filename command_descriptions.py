def localize_command_descriptions(
    commands: Iterable[tuple[str, str]],
) -> list[tuple[str, str]]:
    """Translate known descriptions and preserve unknown plugin commands."""
    return [
        (name, COMMAND_DESCRIPTIONS_RU.get(name, description))
        for name, description in commands
    ]
